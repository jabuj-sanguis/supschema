/** Returns SQL statements generated by drizzle-kit for the exports of a drizzle schema */
const generateSql = async (dialect: DrizzleDialect, imports: Record<string, unknown>) => {
  switch (dialect) {
    case 'postgresql':
      return generateMigration(generateDrizzleJson({}), generateDrizzleJson(imports));
    case 'mysql':
      return generateMySQLMigration(await generateMySQLDrizzleJson({}), await generateMySQLDrizzleJson(imports));
    case 'sqlite':
      return generateSQLiteMigration(await generateSQLiteDrizzleJson({}), await generateSQLiteDrizzleJson(imports));
  }
};

const generateTest = (dialect: DrizzleDialect, schemas: Record<string, RootSchemas>) =>
  generateSql(dialect, drizzleSchema(dialect, schemas));
const generatePostgresTest = (schemas: Record<string, RootSchemas>) => generateTest('postgresql', schemas);
const generateMySqlTest = (schemas: Record<string, RootSchemas>) => generateTest('mysql', schemas);
const generateSqliteTest = (schemas: Record<string, RootSchemas>) => generateTest('sqlite', schemas);

