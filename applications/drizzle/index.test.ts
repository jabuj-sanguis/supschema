it('relations', async () => {
  const Test1 = Model(
    { name: 'Test1', key: ['id'] },
    { id: S.String(), nullableId: S.Nullable(S.String()), parentId: S.Nullable(S.String()) },
  );
  const Test2 = Model({ name: 'Test2', key: ['id'] }, { id: S.String(), arrayId: Unique(S.String()) });

  const schemas = {
    Test1,
    Test2,
    RelOneToOne: ModelRelation(Test1, 'oneToOne', ['id'], Test2, 'oneToOneRev', ['id']),
    RelNullable: ModelRelation(Test1, 'nullable', ['nullableId'], Test2, 'nullableRev', ['id'], {
      onDelete: 'Cascade',
      onUpdate: 'SetNull',
    }),
    RelArray: ModelRelation(Test2, 'array', ['arrayId'], Test1, 'arrayRev', ['id']),
    RelParent: ModelRelation(Test1, 'parent', ['parentId'], Test1, 'children', ['id']),
  };

  const relations = extractTablesRelationalConfig(drizzleSchema('postgresql', schemas), createTableRelationsHelpers);
  const relationTypes = mapValues(relations.tables, (t) =>
    mapValues(t.relations, (r) => `${is(r, One) ? 'one' : 'many'} ${r.referencedTableName} ${r.relationName}`),
  );
  expect(relationTypes).toEqual({
    Test1: {
      oneToOne: 'one Test2 oneToOne',
      nullable: 'one Test2 nullable',
      parent: 'one Test1 parent',
      arrayRev: 'one Test2 array',
      children: 'many Test1 parent',
    },
    Test2: {
      array: 'one Test1 array',
      oneToOneRev: 'one Test1 oneToOne',
      nullableRev: 'many Test1 nullable',
    },
  });

  const sql = await generatePostgresTest(schemas);
  expect(sql).toEqual([
    `CREATE TABLE "Test1" (
\t"id" text PRIMARY KEY NOT NULL,
\t"nullableId" text,
\t"parentId" text
);
`,
    `CREATE TABLE "Test2" (
\t"id" text PRIMARY KEY NOT NULL,
\t"arrayId" text NOT NULL,
\tCONSTRAINT "Test2_arrayId_unique" UNIQUE("arrayId")
);
`,
    `ALTER TABLE "Test1" ADD CONSTRAINT "Test1_id_Test2_id_fk" FOREIGN KEY ("id") REFERENCES "public"."Test2"("id") ON DELETE no action ON UPDATE no action;`,
    `ALTER TABLE "Test1" ADD CONSTRAINT "Test1_nullableId_Test2_id_fk" FOREIGN KEY ("nullableId") REFERENCES "public"."Test2"("id") ON DELETE cascade ON UPDATE set null;`,
    `ALTER TABLE "Test1" ADD CONSTRAINT "Test1_parentId_Test1_id_fk" FOREIGN KEY ("parentId") REFERENCES "public"."Test1"("id") ON DELETE no action ON UPDATE no action;`,
    `ALTER TABLE "Test2" ADD CONSTRAINT "Test2_arrayId_Test1_id_fk" FOREIGN KEY ("arrayId") REFERENCES "public"."Test1"("id") ON DELETE no action ON UPDATE no action;`,
  ]);
});

it('infers types', () => {
  const Status = S.Enum({ active: {}, blocked: {} });
  const User = Model(
    { name: 'User', key: ['id'] },
    {
      id: S.Int32(),
      name: S.String({ maxLength: 10 }),
      status: Status,
      age: S.Nullable(S.SafeInt()),
      balance: S.Int64(),
      tags: S.Array(S.String()),
      settings: S.Object({ theme: S.Nullable(S.Enum({ dark: {}, light: {} })), sizes: S.Array(S.Int16()) }),
    },
  );
  const Post = Model({ name: 'Post', key: ['id'] }, { id: S.String(), userId: S.Int32() });
  const UserPosts = ModelRelation(Post, 'user', ['userId'], User, 'posts', ['id']);

  const schema = drizzleSchema('postgresql', { Status, User, Post, UserPosts });
  expectTypeOf(schema.User.$inferSelect).toEqualTypeOf<{
    id: number;
    name: string;
    status: 'active' | 'blocked';
    age: number | null;
    balance: bigint;
    tags: string[];
    settings: { theme: 'dark' | 'light' | null; sizes: number[] };
  }>();
  expectTypeOf<typeof schema.User._.name>().toEqualTypeOf<'User'>();
  expectTypeOf(schema.Status.enumValues).toEqualTypeOf<['active' | 'blocked', ...('active' | 'blocked')[]]>();
  type PostRelations = ReturnType<typeof schema.PostRelations.config>;
  type UserRelations = ReturnType<typeof schema.UserRelations.config>;
  expectTypeOf<keyof PostRelations>().toEqualTypeOf<'user'>();
  expectTypeOf<PostRelations['user']>().toEqualTypeOf<One<'User'>>();
  expectTypeOf<keyof UserRelations>().toEqualTypeOf<'posts'>();
  expectTypeOf<UserRelations['posts']>().toEqualTypeOf<One<'Post'> | Many<'Post'>>();

  const sqliteSchema = drizzleSchema('sqlite', { User, Post });
  expectTypeOf(sqliteSchema.User.$inferInsert).toEqualTypeOf<{
    id: number;
    name: string;
    status: 'active' | 'blocked';
    age?: number | null;
    balance: bigint;
    tags: string[];
    settings: { theme: 'dark' | 'light' | null; sizes: number[] };
  }>();
  expect(getTableConfig(schema.User).columns.map((c) => c.getSQLType())).toEqual([
    'integer',
    'text',
    'Status',
    'bigint',
    'bigint',
    'text[]',
    'jsonb',
  ]);
});

it('column modifiers and table settings', async () => {
  const Test = Model(
    {
      name: 'Test',
      key: ['id'],
      drizzleTable: {
        extraConfig: (t) => [
          index('Test_tags_gin_idx').using('gin', t.tags),
          check('Test_counter_check', rawSql`${t.counter} >= 0`),
        ],
      },
    },
    {
      id: S.Int32().$drizzle((c) => c.generatedAlwaysAsIdentity()),
      counter: S.Int32().$drizzle((c) => c.default(0)),
      label: Unique(S.String().$drizzle((c) => c.default('none'))),
      note: S.Nullable(S.String().$drizzle((c) => c.default(''))),
      // Modifiers can be chained
      createdAt: S.Int64()
        .$drizzle((c) => c.default(rawSql`0`))
        .$drizzle((c) => c.$onUpdate(() => rawSql`0`)),
      tags: S.Array(S.String()),
    },
  );

  const schema = postgres.drizzleSchema({ Test });
  expectTypeOf(schema.Test.$inferInsert).toEqualTypeOf<{
    counter?: number;
    label?: string;
    note?: string | null;
    createdAt?: bigint;
    tags: string[];
  }>();

  expect(await generateSql('postgresql', schema)).toEqual([
    `CREATE TABLE "Test" (
\t"id" integer PRIMARY KEY GENERATED ALWAYS AS IDENTITY (sequence name "Test_id_seq" INCREMENT BY 1 MINVALUE 1 MAXVALUE 2147483647 START WITH 1 CACHE 1),
\t"counter" integer DEFAULT 0 NOT NULL,
\t"label" text DEFAULT 'none' NOT NULL,
\t"note" text DEFAULT '',
\t"createdAt" bigint DEFAULT 0 NOT NULL,
\t"tags" text[] NOT NULL,
\tCONSTRAINT "Test_label_unique" UNIQUE("label"),
\tCONSTRAINT "Test_counter_check" CHECK ("Test"."counter" >= 0)
);
`,
    `CREATE INDEX "Test_tags_gin_idx" ON "Test" USING gin ("tags");`,
  ]);
});

// Application specific metadata, e.g. a public flag, set by a method returning `this`
const PUB = Symbol('pub');
declare module '@supschema/common-types/DataValue.js' {
  interface DataValue {
    $testPub(): this;
  }
}
extend(S.DataValue, {
  $testPub() {
    return withSchemaMeta(this, PUB, true);
  },
});

it('keeps column types with methods returning this', () => {
  const Test = Model(
    { name: 'Test', key: ['id'] },
    {
      id: S.Int32(),
      pubLast: S.Int32()
        .$drizzle((c) => c.default(1))
        .$testPub(),
      pubFirst: S.Int32()
        .$testPub()
        .$drizzle((c) => c.default(1)),
      chained: S.Int32()
        .$drizzle((c) => c.default(1))
        .$testPub()
        .$drizzle((c) => c.generatedAlwaysAsIdentity()),
      nullable: S.Nullable(S.Int32().$drizzle((c) => c.default(1)).$testPub()),
    },
  );
  const { Test: table } = drizzleSchema('postgresql', { Test });

  expectTypeOf(table.$inferInsert).toEqualTypeOf<{
    id: number;
    pubLast?: number;
    pubFirst?: number;
    nullable?: number | null;
  }>();
  expect(getSchemaMeta(Test.properties.pubLast, PUB)).toBe(true);
  expect(getSchemaMeta(Test.properties.chained, PUB)).toBe(true);
});

it('stores column modifiers as metadata', async () => {
  const pub = <T extends Schema>(schema: T) => withSchemaMeta(schema, PUB, true);

  const schemas = {
    pubFirst: pub(S.Int32()).$drizzle((c) => c.default(1)),
    pubLast: pub(S.Int32().$drizzle((c) => c.default(1))),
    unique: Unique(pub(S.Int32()).$drizzle((c) => c.default(1))),
  };
  for (const schema of Object.values(schemas)) {
    expect(getSchemaMeta(schema, PUB)).toBe(true);
    // The modifier is no option, so it is not serialized
    expect(Object.values(schema).some((v) => typeof v === 'function')).toBe(false);
    expect(extractOptionsModification(schema)?.options ?? {}).not.toHaveProperty('drizzleColumn');
  }
  expect(extractOptionsModification(schemas.unique)?.options).toEqual({ unique: true });

  const Test = Model({ name: 'Test', key: ['id'] }, { id: S.Int32(), ...schemas });
  expect((await generatePostgresTest({ Test }))[0]).toEqual(`CREATE TABLE "Test" (
\t"id" integer PRIMARY KEY NOT NULL,
\t"pubFirst" integer DEFAULT 1 NOT NULL,
\t"pubLast" integer DEFAULT 1 NOT NULL,
\t"unique" integer DEFAULT 1 NOT NULL,
\tCONSTRAINT "Test_unique_unique" UNIQUE("unique")
);
`);
});

it('supports types with columns for some dialects only', async () => {
  const Citext = createType<S.String>(import.meta, S.String);
  extend(Citext, {
    get $drizzleColumn() {
      return columnDef(this, { postgresql: () => pgCustomText() });
    },
  } as never);
  const Test = Model({ name: 'Test', key: ['id'] }, { id: S.Int32(), email: Citext() });

  expect((await generatePostgresTest({ Test }))[0]).toContain('"email" "citext" NOT NULL');
  expect(() => drizzleSchema('mysql', { Test })).toThrow('Property Test.email: Dialect mysql is not supported');
  expect(() => drizzleSchema('sqlite', { Test })).toThrow(UnsupportedDialectError);
});

it('generates schema file', async () => {
  const outputDir = new URL(`./node_modules/.test-output/${crypto.randomUUID()}/`, import.meta.url);
  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(
    new URL('models.ts', outputDir),
    `import { S } from '@supschema/common-types';
import { Model, ModelRelation } from '@supschema/model-types';

export const Test1 = Model({ name: 'Test1', key: ['id'] }, { id: S.String(), status: S.Enum({ a: {} }) });
export const Test2 = Model({ name: 'Test2', key: ['id'] }, { id: S.String(), test1Id: S.String() });
export const Rel = ModelRelation(Test2, 'test1', ['test1Id'], Test1, 'test2s', ['id']);
`,
  );
  const models = await import(new URL('models.ts', outputDir).href);

  const file = generateDrizzleSchemaFile(
    { packageName: new URL('./postgresql.ts', import.meta.url).href },
    { './models.ts': models },
  );
  expect(file.replace(/".*\/postgresql.ts"/, '"@supschema/drizzle/postgresql"'))
    .toEqual(`// This file is generated by @supschema/drizzle. Do not edit it manually.
import { drizzleSchema } from "@supschema/drizzle/postgresql";
import * as schemas from "./models.ts";

export const {
  Test1Status,
  Test1,
  Test2,
  Test1Relations,
  Test2Relations,
} = drizzleSchema({
  Test1: schemas.Test1,
  Test2: schemas.Test2,
  Rel: schemas.Rel,
});
`);

  await fs.writeFile(new URL('schema.ts', outputDir), file);
  const imports = await import(new URL('schema.ts', outputDir).href);
  await fs.rm(outputDir, { recursive: true });
  expect(await generateSql('postgresql', imports)).toHaveLength(4);
});
