it('models', async () => {
  const Test = Model(
    {
      name: 'Test',
      key: ['id', 'test1'],
      indexes: [
        { fields: ['test1', 'test2'] },
        { fields: ['test2'], where: `"test2" <> ''` },
        { fields: ['test1'], name: 'Test_named_idx' },
      ],
      uniques: [{ fields: ['id', 'test1', 'test2'] }, { fields: ['test1', 'test2'], name: 'Test_named_key' }],
    },
    { id: S.String(), test1: Unique(S.String()), test2: S.String() },
  );

  const sql = await generatePostgresTest({ Test });
  expect(sql).toEqual([
    `CREATE TABLE "Test" (
\t"id" text NOT NULL,
\t"test1" text NOT NULL,
\t"test2" text NOT NULL,
\tCONSTRAINT "Test_id_test1_pk" PRIMARY KEY("id","test1"),
\tCONSTRAINT "Test_test1_unique" UNIQUE("test1"),
\tCONSTRAINT "Test_id_test1_test2_unique" UNIQUE("id","test1","test2"),
\tCONSTRAINT "Test_named_key" UNIQUE("test1","test2")
);
`,
    // Without a name the default names of drizzle are used
    `CREATE INDEX "Test_test1_test2_index" ON "Test" USING btree ("test1","test2");`,
    `CREATE INDEX "Test_test2_index" ON "Test" USING btree ("test2") WHERE "test2" <> '';`,
    `CREATE INDEX "Test_named_idx" ON "Test" USING btree ("test1");`,
  ]);

  const { Test: NonPartial } = drizzleSchema('sqlite', {
    Test: Model(
      {
        name: 'Test',
        key: ['id', 'test1'],
        indexes: [{ fields: ['test2'] }, { fields: ['test1'], name: 'Test_named_idx' }],
        uniques: Test.uniques,
      },
      Test.properties,
    ),
  });
  // SQLite requires index names, they are generated in the same way
  expect(getSqliteTableConfig(NonPartial).indexes.map((i) => i.config.name)).toEqual(['Test_test2_index', 'Test_named_idx']);
  expect(getSqliteTableConfig(NonPartial).uniqueConstraints.map((u) => u.name)).toEqual([
    'Test_id_test1_test2_unique',
    'Test_named_key',
  ]);

  expect(() => drizzleSchema('mysql', { Test })).toThrow(
    'Partial indexes are not supported by MySQL',
  );
});

