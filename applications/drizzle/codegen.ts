import fs from 'node:fs/promises';
import { drizzleSchema, DrizzleDialect, getRegisteredDialect, RootSchemas } from './base.js';

export interface DrizzleSchemaFileOptions {
  /** Dialect of the imported entry point, e.g. `@supschema/drizzle/postgresql`, by default */
  dialect?: DrizzleDialect;
  /** Dialect entry point `drizzleSchema` is imported from, `@supschema/drizzle/<dialect>` by default */
  packageName?: string;
}

const isIdentifier = (name: string) => /^[A-Za-z_$][\w$]*$/.test(name);
const member = (obj: string, key: string) => (isIdentifier(key) ? `${obj}.${key}` : `${obj}[${JSON.stringify(key)}]`);

/**
 * Generates a drizzle schema file for drizzle-kit and the application, which calls {@link drizzleSchema}
 * at runtime and exports all tables, relations, enums and database schemas.
 *
 * @param sources Schemas grouped by the module they are imported from in the generated file,
 * e.g. `{ './models.js': { User, Post, UserPosts } }`
 */
export const generateDrizzleSchemaFile = (
  opts: DrizzleSchemaFileOptions,
  sources: Record<string, Record<string, RootSchemas>>,
): string => {
  const dialect = opts.dialect ?? getRegisteredDialect();
  const modules = Object.entries(sources);
  const namespace = (index: number) => (modules.length === 1 ? 'schemas' : `schemas${index + 1}`);

  const properties: string[] = [];
  const schemas: Record<string, RootSchemas> = {};
  modules.forEach(([, moduleSchemas], index) => {
    for (const [name, schema] of Object.entries(moduleSchemas)) {
      if (name in schemas) throw new Error(`Schema ${name} is passed more than once`);
      schemas[name] = schema;
      properties.push(`${isIdentifier(name) ? name : JSON.stringify(name)}: ${member(namespace(index), name)}`);
    }
  });

  const exports = Object.keys(drizzleSchema(dialect, schemas));
  const invalid = exports.filter((name) => !isIdentifier(name));
  if (invalid.length) throw new Error(`Invalid export names: ${invalid.join(', ')}`);

  return [
    '// This file is generated by @supschema/drizzle. Do not edit it manually.',
    `import { drizzleSchema } from ${JSON.stringify(opts.packageName ?? `@supschema/drizzle/${dialect}`)};`,
    ...modules.map(([path], index) => `import * as ${namespace(index)} from ${JSON.stringify(path)};`),
    '',
    'export const {',
    ...exports.map((name) => `  ${name},`),
    '} = drizzleSchema({',
    ...properties.map((p) => `  ${p},`),
    '});',
    '',
  ].join('\n');
};

/**
 * Writes the file generated by {@link generateDrizzleSchemaFile}.
 * Module paths of `sources` must be relative to the written file.
 */
export const writeDrizzleSchemaFile = (
  opts: DrizzleSchemaFileOptions & {
    /** Path of the generated file, `schema.gen.ts` by default */
    path?: string;
  },
  sources: Record<string, Record<string, RootSchemas>>,
) => fs.writeFile(opts.path ?? 'schema.gen.ts', generateDrizzleSchemaFile(opts, sources));
